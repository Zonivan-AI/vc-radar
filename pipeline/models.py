# PortfolioCompany (lightweight extraction result)
# ---------------------------------------------------------------------------


class PortfolioCompany(BaseModel):
    """Lightweight company record returned from HTML extraction.

    Subset of CompanyRecord — used during pipeline ingestion before
    database UUIDs are assigned.
    """

    name: str = Field(..., min_length=1)
    slug: str = Field(..., min_length=1)
    sector: str | None = None
    subsector: str | None = None
    description: str | None = None
    website: str | None = None
    founded_year: int | None = None
    city: str | None = None
    country: str | None = None
    stage: CompanyStage | None = None
    status: CompanyStatus = "Active"
    status_detail: str | None = None
    source_url: str | None = None
    founders: list[dict[str, Any]] = Field(
        default_factory=list,
        description="Raw founder dicts from extraction (name + role only)",
    )

    @field_validator("founded_year")
    @classmethod
    def validate_founded_year(cls, v: int | None) -> int | None:
        if v is not None and not (MIN_FOUNDING_YEAR <= v <= MAX_FOUNDING_YEAR):
            raise ValueError(
                f"founded_year must be between {MIN_FOUNDING_YEAR} and {MAX_FOUNDING_YEAR}, got {v}"
            )
        return v

    def to_company_record(self) -> CompanyRecord:
        """Promote to a full CompanyRecord (without id/timestamps)."""
        return CompanyRecord(
            name=self.name,
            slug=self.slug,
            sector=self.sector,
            subsector=self.subsector,
            description=self.description,
            website=self.website,
            founded_year=self.founded_year,
            city=self.city,
            country=self.country,
            stage=self.stage,
            status=self.status,
            status_detail=self.status_detail,
            source_url=self.source_url,
        )


# ---------------------------------------------------------------------------
# PortfolioExtractionResult
# ---------------------------------------------------------------------------


class PortfolioExtractionResult(BaseModel):
    """Top-level result from a single pipeline run against one VC firm."""

    vc_slug: str
    vc_name: str
    source_url: str
    companies: list[PortfolioCompany] = Field(default_factory=list)
    companies_found: int = 0
    errors: list[str] = Field(default_factory=list)
    tokens_used: int = 0
    cost_usd: float = 0.0
    model_used: str = ""

    @model_validator(mode="after")
    def sync_companies_found(self) -> "PortfolioExtractionResult":
        """Keep companies_found in sync with the actual companies list."""
        if self.companies_found == 0 and self.companies:
            self.companies_found = len(self.companies)
        return self
