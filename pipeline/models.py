    est_birth_year: int | None = None
    domain_exp_years: int | None = None
    prior_founder: bool = False
    education_tier: EducationTier | None = None
    university: str | None = None
    degree: str | None = None
    grad_year: int | None = None
    age_at_founding: int | None = None                # founded_year - est_birth_year
    current_age_2026: int | None = None               # 2026 - est_birth_year
    age_confidence: AgeConfidence = "Low"
    age_inference_method: str | None = None
    linkedin_url: str | None = None
    twitter_url: str | None = None
    nationality: str | None = None
    source_notes: str | None = None
    created_at: datetime | None = None

    @field_validator("est_birth_year")
    @classmethod
    def validate_birth_year(cls, v: int | None) -> int | None:
        if v is not None and not (MIN_BIRTH_YEAR <= v <= MAX_BIRTH_YEAR):
            raise ValueError(
                f"est_birth_year must be between {MIN_BIRTH_YEAR} and {MAX_BIRTH_YEAR}, got {v}"
            )
        return v

    @field_validator("grad_year")
    @classmethod
    def validate_grad_year(cls, v: int | None) -> int | None:
        if v is not None and not (1950 <= v <= MAX_FOUNDING_YEAR):
            raise ValueError(
                f"grad_year must be between 1950 and {MAX_FOUNDING_YEAR}, got {v}"
            )
        return v

    @field_validator("domain_exp_years")
    @classmethod
    def validate_domain_exp_years(cls, v: int | None) -> int | None:
        if v is not None and not (0 <= v <= 60):
            raise ValueError("domain_exp_years must be between 0 and 60")
        return v

    @field_validator("age_at_founding", "current_age_2026")
    @classmethod
    def validate_ages(cls, v: int | None) -> int | None:
        if v is not None and not (0 <= v <= 100):
            raise ValueError("age values must be between 0 and 100")
        return v


