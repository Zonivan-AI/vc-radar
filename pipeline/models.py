# ---------------------------------------------------------------------------
# FounderAgeResult
# ---------------------------------------------------------------------------


class FounderAgeResult(BaseModel):
    """Result from the triangulator — age estimation for a single founder.

    Returned by triangulate_founder_age() in triangulator.py.
    """

    founder_name: str
    company_name: str
    est_birth_year: int | None = None
    age_at_founding: int | None = None
    current_age_2026: int | None = None
    age_confidence: AgeConfidence = "Low"
    age_inference_method: str | None = None
    reasoning: str | None = Field(
        None,
        description="Claude's step-by-step reasoning for the age estimate",
    )
    sources_used: list[str] = Field(
        default_factory=list,
        description="List of evidence types used (e.g. 'graduation year', 'LinkedIn')",
    )
    raw_response: str | None = Field(
        None,
        description="Raw text response from Claude for audit purposes",
        exclude=True,
    )

    @field_validator("est_birth_year")
    @classmethod
    def validate_birth_year(cls, v: int | None) -> int | None:
        if v is not None and not (MIN_BIRTH_YEAR <= v <= MAX_BIRTH_YEAR):
            raise ValueError(
                f"est_birth_year must be between {MIN_BIRTH_YEAR} and {MAX_BIRTH_YEAR}, got {v}"
            )
        return v

    @model_validator(mode="after")
    def compute_derived_ages(self) -> "FounderAgeResult":
        """Auto-compute current_age_2026 from est_birth_year if not set."""
        if self.est_birth_year is not None and self.current_age_2026 is None:
            self.current_age_2026 = 2026 - self.est_birth_year
        return self


