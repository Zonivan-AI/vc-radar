class FounderRecord(BaseModel):
    """Maps to the `founders` table."""

    id: str | None = None                              # UUID, generated by DB
    company_id: str = Field(..., description="UUID of the parent portfolio_companies row")
    full_name: str = Field(..., min_length=1)
