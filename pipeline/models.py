"""
Pydantic V2 shared models for the Meridian VC Intelligence pipeline.

These models mirror the database/schema.sql table structures exactly,
including column names, types, and CHECK constraint enums.
"""

from __future__ import annotations

from datetime import date, datetime
from typing import Annotated, Any, Literal

from pydantic import BaseModel, Field, field_validator, model_validator


# ---------------------------------------------------------------------------
# Enums (matching schema CHECK constraints)
# ---------------------------------------------------------------------------

DataQuality = Literal["high", "medium", "low"]
CompanyStatus = Literal["Active", "Acquired", "IPO", "Shutdown", "Unknown"]
CompanyStage = Literal[
    "Pre-Seed", "Seed", "Early",
    "Series A", "Series B", "Series C", "Series D", "Series E",
    "Growth",
]
FounderRole = Literal["primary", "co-founder"]
EducationTier = Literal["Top-10", "Top-50", "Other"]
AgeConfidence = Literal["High", "Medium", "Low"]
EntityType = Literal["company", "founder", "vc_firm", "funding_round"]
SourceType = Literal["manual", "exa", "serper", "playwright", "sec_edgar", "user_submission"]
PipelineStatus = Literal["running", "completed", "failed", "partial"]

# Year range constants
MIN_FOUNDING_YEAR = 1900
MAX_FOUNDING_YEAR = 2030
MIN_BIRTH_YEAR = 1940
MAX_BIRTH_YEAR = 2010


# ---------------------------------------------------------------------------
# VCFirmRecord
# ---------------------------------------------------------------------------


class VCFirmRecord(BaseModel):
    """Maps to the `vc_firms` table."""

    id: str | None = None                              # UUID, generated by DB
    name: str = Field(..., min_length=1)
    slug: str = Field(..., min_length=1, pattern=r"^[a-z0-9-]+$")
    website: str | None = None
    description: str | None = None
    hq_city: str | None = None
    hq_country: str | None = None
    hq_region: str | None = None
    founded_year: int | None = None
    aum_usd: int | None = None
    fund_stage: list[str] = Field(default_factory=list)
    focus_sectors: list[str] = Field(default_factory=list)
    logo_url: str | None = None
    linkedin_url: str | None = None
    data_quality: DataQuality = "medium"
    created_at: datetime | None = None
    updated_at: datetime | None = None

    @field_validator("founded_year")
    @classmethod
    def validate_founded_year(cls, v: int | None) -> int | None:
        if v is not None and not (MIN_FOUNDING_YEAR <= v <= MAX_FOUNDING_YEAR):
            raise ValueError(
                f"founded_year must be between {MIN_FOUNDING_YEAR} and {MAX_FOUNDING_YEAR}, got {v}"
            )
        return v

    @field_validator("aum_usd")
    @classmethod
    def validate_aum_usd(cls, v: int | None) -> int | None:
        if v is not None and v < 0:
            raise ValueError("aum_usd must be non-negative")
        return v


